// Writes src/standalone-helpers.js: the source of the library functions that standalone code calls, as text (see
// standalone.js), with the other helpers each one calls. Run it (npm run build:helpers) after changing one of them;
// test/standalone.test.js checks that each copy behaves as the function it copies.
const fs = require('fs');
const path = require('path');
const { deepEqual } = require('../src/deep-equal');
const { codePointLength } = require('../src/types/code-point-length');
const { hasDuplicates } = require('../src/types/has-duplicates');
const { FORMAT_FUNCTIONS } = require('../src/formats');
const { errorObject, pathName } = require('../src/error-objects');

const functions = { codePointLength, deepEqual, hasDuplicates, pathName, errorObject, ...FORMAT_FUNCTIONS };
const names = Object.keys(functions);

let out = `// Generated by scripts/generate-standalone-helpers.js (npm run build:helpers): do not edit.
// Source of the library functions that standalone code calls, written into it (see standalone.js). They are kept as
// text rather than read with toString(), which tools that rewrite code (coverage, minifiers) change.
// test/standalone.test.js checks that each one behaves as the library function it copies.
/* eslint-disable no-template-curly-in-string -- the sources are code, with template literals */
const HELPER_SOURCES = {
`;
names.forEach((name) => {
  const source = functions[name].toString();
  if (!source.startsWith(`function ${name}(`)) {
    throw new Error(`The source of ${name} does not start with "function ${name}(": run this script on plain source`);
  }
  // The other helpers it calls by name.
  const calls = names.filter((other) => other !== name && new RegExp(`\\b${other}\\b`).test(source));
  const lines = source
    .split('\n')
    .map((line) => `      ${JSON.stringify(line)},`)
    .join('\n');
  out += `  ${name}: {\n    calls: [${calls.map((call) => `'${call}'`).join(', ')}],\n    source: [\n${lines}\n    ].join('\\n'),\n  },\n`;
});
out += '};\n\nmodule.exports = { HELPER_SOURCES };\n';

fs.writeFileSync(path.join(__dirname, '../src/standalone-helpers.js'), out);
console.log(`Wrote src/standalone-helpers.js with ${names.length} helpers`);
